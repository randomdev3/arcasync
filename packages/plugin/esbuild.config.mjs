import { execSync } from "node:child_process";
import fs from "node:fs";
import { builtinModules } from "node:module";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import esbuild from "esbuild";
import esbuildSvelte from "esbuild-svelte";
import sveltePreprocess from "svelte-preprocess";

const here = path.dirname(fileURLToPath(import.meta.url));
const outdir = path.join(here, "dist");

const mode = process.argv[2] ?? "production";
const watch = mode === "watch";
const debug = watch || mode === "debug";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
If you want to view the source, visit the TeamSync repository.
*/
`;

const gitTag = (() => {
	try {
		return execSync("git describe --tags --always", {
			cwd: here,
			encoding: "utf8",
			stdio: ["ignore", "pipe", "ignore"],
		}).trim();
	} catch {
		return "dev";
	}
})();

/**
 * Resolve a package's on-disk root through Node resolution so this works with
 * pnpm's symlinked, non-hoisted `node_modules`.
 */
const packageRoot = (specifier) => {
	const entry = fileURLToPath(import.meta.resolve(specifier));
	let dir = path.dirname(entry);
	while (!fs.existsSync(path.join(dir, "package.json"))) {
		const parent = path.dirname(dir);
		if (parent === dir) throw new Error(`cannot locate package root for ${specifier}`);
		dir = parent;
	}
	return dir;
};

/**
 * Yjs ships both a bundled `dist/` build and its ES sources. Anything importing
 * `yjs/dist/src/internals` (y-protocols, y-codemirror.next, @hocuspocus/provider)
 * must land on the SAME module graph as `yjs`, or `instanceof Item`/`GC` checks
 * across the boundary silently fail in the bundle.
 */
const yjsRoot = packageRoot("yjs");
const YjsInternalsPlugin = {
	name: "yjs-internals",
	setup(build) {
		build.onResolve({ filter: /^yjs$/ }, () => ({
			path: path.join(yjsRoot, "src/index.js"),
		}));
		build.onResolve({ filter: /^yjs\/dist\/src\/internals$/ }, () => ({
			path: path.join(yjsRoot, "src/internals.js"),
		}));
	},
};

/**
 * Svelte's Trusted Types policy uses an arrow function that returns the string
 * unchanged. In an Obsidian popout window the arrow belongs to the main window's
 * realm, and Chromium rejects the cross-realm result. `String` is realm-neutral.
 */
const SvelteTrustedTypesPlugin = {
	name: "svelte-trusted-types",
	setup(build) {
		build.onLoad(
			{ filter: /[\\/]svelte[\\/]src[\\/]internal[\\/]client[\\/]dom[\\/]reconciler\.js$/ },
			async (args) => {
				const source = await fs.promises.readFile(args.path, "utf8");
				const callback = /createHTML: \(html\) => \{\s*return html;\s*\}/;
				if (!callback.test(source)) {
					throw new Error(
						"Svelte's Trusted Types callback changed; update the realm-neutral rewrite",
					);
				}
				return { contents: source.replace(callback, "createHTML: String"), loader: "js" };
			},
		);
	},
};

const staticFiles = ["manifest.json", "styles.css"];

const copyStaticFiles = () => {
	fs.mkdirSync(outdir, { recursive: true });
	for (const name of staticFiles) {
		fs.copyFileSync(path.join(here, name), path.join(outdir, name));
	}
};

const touchHotReload = () => {
	fs.writeFileSync(path.join(outdir, ".hotreload"), "");
};

const HotReloadPlugin = {
	name: "hot-reload",
	setup(build) {
		build.onEnd((result) => {
			if (result.errors.length > 0) return;
			copyStaticFiles();
			if (watch) touchHotReload();
		});
	},
};

/**
 * A second copy of Yjs in the bundle is a silent correctness bug — `instanceof
 * Item`/`GC` checks across the two graphs quietly disagree — so fail the build
 * instead of shipping it. This string literal lives in `AbstractType.js` and
 * survives minification, unlike any identifier.
 */
export const YJS_BUNDLE_MARKER = "Invalid access: Add Yjs type to a document before reading data.";

const assertSingleYjsCopy = () => {
	const bundle = fs.readFileSync(path.join(outdir, "main.js"), "utf8");
	const hits = bundle.split(YJS_BUNDLE_MARKER).length - 1;
	if (hits !== 1) {
		throw new Error(`expected exactly 1 copy of yjs in dist/main.js, found ${hits}`);
	}
	console.log("yjs copies in bundle: 1");
};

const options = {
	banner: { js: banner },
	entryPoints: [path.join(here, "src/main.ts")],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"moment",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
	],
	format: "cjs",
	platform: "browser",
	target: "es2022",
	plugins: [
		SvelteTrustedTypesPlugin,
		esbuildSvelte({
			compilerOptions: { css: "injected" },
			preprocess: sveltePreprocess(),
		}),
		YjsInternalsPlugin,
		HotReloadPlugin,
	],
	treeShaking: true,
	minify: !debug,
	sourcemap: debug ? "inline" : false,
	logLevel: "info",
	define: {
		BUILD_TYPE: debug ? '"debug"' : '"prod"',
		GIT_TAG: `"${gitTag}"`,
	},
	outdir,
};

if (watch) {
	const ctx = await esbuild.context(options);
	await ctx.watch();
} else {
	await esbuild.build(options);
	assertSingleYjsCopy();
}
