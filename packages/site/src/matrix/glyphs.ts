/** Rows of `#`/`R`/`.` for a word in the 5×7 alphabet, one blank column between letters. */
export function wordRows(word: string, first?: string[]): string[] {
	const rows = Array.from({ length: GLYPH_H }, () => "");
	[...word].forEach((ch, i) => {
		const glyph = (i === 0 && first) || GLYPHS[ch] || GLYPHS[" "];
		for (let y = 0; y < GLYPH_H; y++) rows[y] += `${i ? "." : ""}${glyph?.[y] ?? "....."}`;
	});
	return rows;
}
